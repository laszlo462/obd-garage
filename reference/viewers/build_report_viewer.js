// Builds a self-contained viewer for OBDLink "Diagnostic Report" HTML exports.
//   node build_report_viewer.js                      (every data/*/Diagnostic*Report*.html)
//   node build_report_viewer.js <report.html> [...]  (just these)
//   node build_report_viewer.js --app [outdir]       (hostable web app, default outdir report-app/)
// Writes report_viewer.html next to this script. Node only, no dependencies.
//
// The builder does no parsing. It embeds each report's raw HTML, and the page parses it in the
// browser, so the same page can also open more reports by drag-and-drop or "Add report".
//
// --app builds the same page with no reports embedded, for hosting on any static web server.
// Reports added there are saved in that browser's IndexedDB. It also writes a web-app manifest,
// an icon and a service worker (offline use; browsers only run it over https or on localhost).
// Only the Mode $06 test notes carry over; report notes are keyed by file name and don't apply.
//
// Optional notes: reports/report-notes.json. Every key is optional.
//   reports  { "<report basename, no .html>": { note, warnings: [string] } }
//            note shows under the title; warnings show as banners (e.g. a post-regen read).
//   tests    { "$34": text, "$34 $90": text }  notes on a Mode $06 MID or MID + TID, shown in every report
const fs = require("fs");
const path = require("path");

const args = process.argv.slice(2);
const appMode = args[0] === "--app";
const notesPath = path.join(__dirname, "reports", "report-notes.json");
const notes = fs.existsSync(notesPath) ? JSON.parse(fs.readFileSync(notesPath, "utf8")) : {};

// "<" escaped so report markup can't close the <script> it is embedded in.
const js = (v) => JSON.stringify(v).replace(/</g, "\\u003c");
const tpl = fs.readFileSync(path.join(__dirname, "report_viewer_template.html"), "utf8");
// The template's placeholder line keeps it usable unbuilt (empty, drag-and-drop only).
const fill = (reports, notes, save, head) => tpl
  .replace("/*__DATA__*/const REPORTS = [], NOTES = {}, SAVE = false;",
    () => `const REPORTS = ${js(reports)};\nconst NOTES = ${js(notes)};\nconst SAVE = ${save};`)
  .replace("<!--__APP_HEAD__-->", () => head);

if (appMode) {
  const outDir = path.resolve(args[1] || path.join(__dirname, "report-app"));
  fs.mkdirSync(outDir, { recursive: true });
  const head = [
    '<link rel="manifest" href="manifest.webmanifest">',
    '<link rel="icon" href="icon.svg" type="image/svg+xml">',
    '<meta name="theme-color" content="#2a78d6">',
  ].join("\n");
  const stamp = new Date().toISOString();
  const files = {
    "index.html": fill([], { tests: notes.tests || {} }, true, head),
    "manifest.webmanifest": JSON.stringify({
      name: "OBDLink report viewer", short_name: "OBD reports", start_url: "./", scope: "./",
      display: "standalone", background_color: "#16181d", theme_color: "#2a78d6",
      icons: [{ src: "icon.svg", sizes: "any", type: "image/svg+xml", purpose: "any" }],
    }, null, 2),
    "icon.svg": `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="#2a78d6"/>` +
      `<path d="M10 44h44M14 44l9-18 9 10 8-16 10 24" fill="none" stroke="#fff" stroke-width="5" stroke-linecap="round" stroke-linejoin="round"/></svg>\n`,
    // Network first, so a redeploy shows up on the next visit; the cache is only the offline fallback.
    "sw.js": `// Built ${stamp}. Generated by build_report_viewer.js --app.
const CACHE = "obdlink-report-viewer-${stamp}";
const FILES = ["./", "index.html", "manifest.webmanifest", "icon.svg"];
self.addEventListener("install", (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES))); self.skipWaiting(); });
self.addEventListener("activate", (e) => e.waitUntil(caches.keys()
  .then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(fetch(e.request).then((r) => { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); return r; })
    .catch(() => caches.match(e.request, { ignoreSearch: true })));
});
`,
  };
  for (const [f, body] of Object.entries(files)) fs.writeFileSync(path.join(outDir, f), body);
  console.log(`wrote ${outDir} (${Object.keys(files).join(", ")})`);
  process.exit(0);
}

const dataDir = path.join(__dirname, "..", "data");
let files = args;
if (!files.length) {
  for (const d of fs.readdirSync(dataDir).sort()) {
    const dir = path.join(dataDir, d);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const f of fs.readdirSync(dir).sort())
      if (/^diagnostic[ _]report.*\.html?$/i.test(f)) files.push(path.join(dir, f));
  }
}
if (!files.length) { console.error("no reports found"); process.exit(1); }

const reports = files.map((f) => ({ name: path.basename(f).replace(/\.html?$/i, ""), html: fs.readFileSync(f, "utf8") }));
const outPath = path.join(__dirname, "report_viewer.html");
fs.writeFileSync(outPath, fill(reports, notes, false, ""));
console.log(`wrote ${outPath} (${reports.length} report${reports.length === 1 ? "" : "s"}: ${reports.map((r) => r.name).join(", ")})`);
